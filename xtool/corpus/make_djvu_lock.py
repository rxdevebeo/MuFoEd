#!/usr/bin/env python3
"""Generate `testdata-lock/djvu.toml` from `testdata/CC0_DJVU/manifest.json`.

The DjVu validation corpus is the CC0 collection the owner keeps under
`testdata/CC0_DJVU/`. Like the WordprocessingML corpus, the bytes are never
committed: only this lock file is, one `[[doc]]` per document with a stable id,
the path under `testdata/`, the SHA-256 and size, the archive.org URL and the
tier. `cargo run -p xtool -- corpus fetch --lock testdata-lock/djvu.toml
--tier djvu` downloads the bytes and checks every hash.

The manifest records `byte_size` but no hash, so the hash is taken from the
local file and the size is checked against the manifest. Every document must be
present under `--root`, because that local copy is what is hashed.

The output is deterministic: documents are sorted by id and nothing time- or
machine-dependent is written.

Usage:
    python3 xtool/corpus/make_djvu_lock.py --root /path/to/testdata [--out testdata-lock/djvu.toml]
    python3 xtool/corpus/make_djvu_lock.py --root ... --check   # exit 1 if the lock is stale
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
DEFAULT_OUT = os.path.join(REPO, "testdata-lock", "djvu.toml")

DIRECTORY = "CC0_DJVU"
TIER = "djvu"
LICENSE_URLS = {
    "http://creativecommons.org/publicdomain/zero/1.0/",
    "https://creativecommons.org/publicdomain/zero/1.0/",
}


def sha256_of(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def collect(root: str) -> list[dict]:
    manifest_path = os.path.join(root, DIRECTORY, "manifest.json")
    with open(manifest_path, encoding="utf-8") as handle:
        manifest = json.load(handle)
    docs = []
    for entry in manifest:
        name = entry["local_filename"]
        identifier = entry["identifier"]
        if entry["license_url"] not in LICENSE_URLS:
            raise SystemExit(f"error: {name}: licence {entry['license_url']}")
        url = entry["download_url"]
        if not url.startswith("https://archive.org/"):
            raise SystemExit(f"error: {name}: url {url} is not archive.org")
        path = os.path.join(root, DIRECTORY, name)
        if not os.path.isfile(path):
            raise SystemExit(f"error: {path} is missing; the hash needs the local copy")
        size = os.path.getsize(path)
        if size != entry["byte_size"]:
            raise SystemExit(f"error: {name}: {size} bytes, the manifest records {entry['byte_size']}")
        docs.append(
            {
                "id": f"djvu/{identifier}",
                "path": f"{DIRECTORY}/{name}",
                "sha256": sha256_of(path),
                "bytes": size,
                "url": url,
                "license": "CC0-1.0",
                "source_manifest": f"{DIRECTORY}/manifest.json",
                "tiers": [TIER],
            }
        )
    ids = [doc["id"] for doc in docs]
    if len(set(ids)) != len(ids):
        raise SystemExit("error: duplicate ids")
    docs.sort(key=lambda doc: doc["id"])
    return docs


def quote(value: str) -> str:
    # A JSON string with non-ASCII kept is a valid TOML basic string.
    return json.dumps(value, ensure_ascii=False)


def render(docs: list[dict]) -> str:
    lines = [
        "# DjVu validation corpus lock (STAGE-9-TASK.md).",
        "#",
        "# GENERATED by `python3 xtool/corpus/make_djvu_lock.py --root <testdata>`; do not edit.",
        "# The documents themselves are never committed:",
        "#   cargo run -p xtool -- corpus fetch --lock testdata-lock/djvu.toml --tier djvu",
        "# downloads them into testdata/ and checks every hash.",
        "#",
        f"# {len(docs)} documents, {sum(d['bytes'] for d in docs)} bytes; tier: {TIER}.",
        "",
        "schema = 1",
    ]
    for doc in docs:
        lines.append("")
        lines.append("[[doc]]")
        lines.append(f"id = {quote(doc['id'])}")
        lines.append(f"path = {quote(doc['path'])}")
        lines.append(f"sha256 = {quote(doc['sha256'])}")
        lines.append(f"bytes = {doc['bytes']}")
        lines.append(f"url = {quote(doc['url'])}")
        lines.append(f"license = {quote(doc['license'])}")
        lines.append(f"source_manifest = {quote(doc['source_manifest'])}")
        lines.append("tiers = [" + ", ".join(quote(t) for t in doc["tiers"]) + "]")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=os.path.join(REPO, "testdata"))
    parser.add_argument("--out", default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="fail if --out differs")
    args = parser.parse_args(argv)
    text = render(collect(args.root))
    if args.check:
        try:
            with open(args.out, encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print(f"error: {args.out} is stale; rerun make_djvu_lock.py", file=sys.stderr)
            return 1
        print(f"ok: {args.out} is current")
        return 0
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
