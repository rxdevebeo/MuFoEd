"""Build the metric profiles of proprietary families from a host font inventory.

    python xtool/fonts/build_metric_profiles.py wps-qa/host-fonts.json \
        strict-ooxml-render-svg/src/font/profiles_data.rs

A profile is the measure of a family the renderer has no metric-compatible
open face for (Verdana, Lucida Sans Unicode, Candara, ...): its Windows line
box and the advance widths of the Latin, Greek, Cyrillic and punctuation
characters. The text is drawn with a bundled face (`SUBSTITUTE`) placed at the
profile's advances, so lines break and stack where Word and WPS put them.
Only numbers are taken from the fonts (`xtool/wps-qa/host_fonts.py`).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# Requested family -> (bundled face that draws it, extra request names).
PROFILES = {
    "Lucida Sans Unicode": ("Arimo", ["lucidasansunicode"]),
    "Verdana": ("Arimo", []),
    "Tahoma": ("Arimo", []),
    "Trebuchet MS": ("Arimo", ["trebuchet"]),
    "Microsoft Sans Serif": ("Arimo", ["ms sans serif"]),
    "Franklin Gothic Medium": ("Arimo", ["franklin gothic"]),
    "Comic Sans MS": ("Arimo", ["comic sans"]),
    "Calibri Light": ("Carlito", []),
    "Candara": ("Carlito", []),
    "Candara Light": ("Carlito", []),
    "Corbel": ("Carlito", []),
    "Corbel Light": ("Carlito", []),
    "Constantia": ("Caladea", []),
    "Palatino Linotype": ("Tinos", ["palatino", "book antiqua"]),
    "Sylfaen": ("Tinos", []),
    "Consolas": ("Cousine", []),
    "Lucida Console": ("Cousine", []),
}


def faces_of(inventory: dict, family: str) -> list[dict]:
    """Faces whose legacy (RIBBI) family is `family`: Calibri Light is its
    own family there, as Word names it."""
    return [f for f in inventory["faces"] if f.get("legacy_family") == family]


def runs(advances: dict) -> list[tuple[int, list[int]]]:
    items = sorted((int(k), v) for k, v in advances.items())
    out: list[tuple[int, list[int]]] = []
    for code, adv in items:
        if out and out[-1][0] + len(out[-1][1]) == code:
            out[-1][1].append(adv)
        else:
            out.append((code, [adv]))
    return out


def rust(inventory: dict) -> str:
    lines = [
        "// @generated by xtool/fonts/build_metric_profiles.py from a host font",
        "// inventory (xtool/wps-qa/host_fonts.py). Metrics only: line boxes and",
        "// advance widths, in font units. Do not edit by hand.",
        "",
        "use super::{MetricProfile, ProfileFace};",
        "",
        "pub(super) static PROFILES: &[MetricProfile] = &[",
    ]
    for family, (substitute, extra) in PROFILES.items():
        faces = faces_of(inventory, family)
        if not faces:
            print(f"warning: {family} not in the inventory", file=sys.stderr)
            continue
        names = sorted({family.lower(), *extra})
        alias = f"{substitute} for {family}"
        lines.append("    MetricProfile {")
        lines.append(f'        family: "{alias}",')
        lines.append(f"        requested: &{json.dumps(names)},")
        lines.append(f'        substitute: "{substitute}",')
        lines.append("        faces: &[")
        seen = set()
        for f in sorted(faces, key=lambda f: (f["bold"], f["italic"])):
            key = (f["bold"], f["italic"])
            if key in seen or "win" not in f:
                continue
            seen.add(key)
            body = ", ".join(f"({start}, &{json.dumps(advs, separators=(',', ':'))})" for start, advs in runs(f["advances"]))
            lines.append("            ProfileFace {")
            lines.append(f"                bold: {str(f['bold']).lower()},")
            lines.append(f"                italic: {str(f['italic']).lower()},")
            lines.append(f"                units_per_em: {f['units_per_em']},")
            lines.append(f"                ascent: {f['win'][0]},")
            lines.append(f"                descent: {f['win'][1]},")
            lines.append(f"                runs: &[{body}],")
            lines.append("            },")
        lines.append("        ],")
        lines.append("    },")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    inventory = json.loads(Path(argv[0]).read_text(encoding="utf-8"))
    Path(argv[1]).write_text(rust(inventory), encoding="utf-8")
    print(f"wrote {argv[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
